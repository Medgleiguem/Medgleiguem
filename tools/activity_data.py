"""Derive truthful calendar metrics and native text from the allowlisted snapshot."""
from collections import defaultdict
from datetime import date, timedelta
from html import escape


TYPE_LABELS = [('commits','Commits'), ('pull_requests','Pull requests opened'),
               ('issues','Issues opened'), ('reviews','Pull request reviews')]


def calendar_days(data):
    end = date.fromisoformat(data['window']['end'])
    start = max(date.fromisoformat(data['window']['start']), end-timedelta(days=365))
    counts = {date.fromisoformat(item['date']):item['count'] for item in data['calendar']}
    return [(start+timedelta(days=i), counts.get(start+timedelta(days=i),0))
            for i in range((end-start).days+1)]


def calendar_stats(data):
    days = calendar_days(data)
    counts = dict(days)
    today = date.fromisoformat(data['as_of'])
    current, longest, run = 0, 0, 0
    anchor = today if counts.get(today,0) else today-timedelta(days=1)
    while counts.get(anchor,0):
        current += 1
        anchor -= timedelta(days=1)
    for _,count in days:
        run = run+1 if count else 0
        longest = max(longest,run)
    return {'contributions':sum(n for _,n in days), 'active_days':sum(n>0 for _,n in days),
            'current_streak':current, 'longest_streak':longest,
            'last_30_days':sum(n for day,n in days if today-timedelta(days=29)<=day<=today)}


def weekly_totals(days, limit=13):
    weeks = defaultdict(int)
    for day,count in days:
        weeks[day-timedelta(days=(day.weekday()+1)%7)] += count
    return sorted(weeks.items())[-limit:]


def language_shares(data):
    languages = sorted(({'name':x['name'],'bytes':x['bytes']} for x in data.get('public_languages',[]) if x['bytes']>0),
                       key=lambda x:(-x['bytes'],x['name']))
    if len(languages)>5:
        languages = languages[:4]+[{'name':'Other','bytes':sum(x['bytes'] for x in languages[4:])}]
    total = sum(x['bytes'] for x in languages)
    return [dict(x,percent=100*x['bytes']/total) for x in languages]


def activity_summary(data):
    """Native equivalent of the visual board, generated by both refresh paths."""
    days, stats = calendar_days(data), calendar_stats(data)
    lines = ['# GitHub activity', '',
             f'Calendar: **{days[0][0]} → {days[-1][0]}**. Snapshot: **{data["updated_at"]}**.', '',
             '| Calendar metric | Value |','| --- | ---: |']
    for key,label in [('contributions','Calendar contributions'),('active_days','Active days'),
                      ('current_streak','Current streak (days)'),('longest_streak','Longest streak (days)'),
                      ('last_30_days','Last 30 days')]:
        lines.append(f'| {label} | {stats[key]:,} |')
    lines += ['', 'Current streak ends today or yesterday. Longest streak covers the displayed calendar. '
              'Days missing inside the returned date window count as zero. Contributions are GitHub-visible activity, not work hours or a quality rating.', '',
              '## Contribution types', '']
    window = data.get('collection_window')
    if window:
        lines.append(f'API collection: **{window["start"]} → {window["end"]}**.')
    else:
        lines.append('API collection dates are unavailable in this snapshot.')
    lines += ['', '| API contribution type | Count |','| --- | ---: |']
    for key,label in TYPE_LABELS:
        value = data.get('contribution_types',{}).get(key)
        lines.append(f'| {label} | {value:,} |' if value is not None else f'| {label} | Unavailable |')
    lines += ['', 'These are separate GitHub API collection counters. They reflect accessible contributions; '
              'they are not a partition of the calendar total, and unavailable values are not zero.', '',
              '## Recent weekly activity', '', '| Week beginning Sunday | Calendar contributions |','| --- | ---: |']
    lines += [f'| {day} | {count:,} |' for day,count in weekly_totals(days)]
    lines += ['', 'The first and last weeks may be partial.', '', '## Public code languages', '',
              'Public repositories only. Shares describe source bytes, not proficiency or the full professional toolkit.', '',
              '| Language | Source bytes | Share |','| --- | ---: | ---: |']
    for item in language_shares(data):
        name = escape(item['name']).replace('|','\\|').replace('\n',' ')
        lines.append(f'| {name} | {item["bytes"]:,} | {item["percent"]:.1f}% |')
    if not language_shares(data):
        lines.append('| No public language bytes available | — | — |')
    lines += ['', '[Raw snapshot](../data/activity.json) · [Profile](../README.md#user-content-workbench)', '',
              'Source definitions: [GitHub ContributionsCollection](https://docs.github.com/en/graphql/reference/users#contributionscollection).', '']
    return '\n'.join(lines)
